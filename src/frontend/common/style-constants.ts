/**
 * Standard icon sizes to pass to Tabler icons.
 */
export enum IconSize {
    /** Things like icons on badges */
    TINY = 12,
    /** Things like menu options */
    SMALL = 16,
    /** Things like buttons */
    MEDIUM = 18,
    /** In-line error states */
    LARGE = 36,
    /** Full-page error states */
    HUGE = 48
}
